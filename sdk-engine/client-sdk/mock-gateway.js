import express from "express";

const app = express();
const PORT = 5000;

app.use(express.json());

app.get("/health", (req, res) => {
  res.json({
    success: true,
    message: "Mock OneAPI Gateway is running",
  });
});

app.post("/api/v1/proxy/ai/chat", async (req, res) => {
  try {
    // 1. Validate OneAPI credentials
    const authorization = req.headers.authorization;
    const projectId = req.headers["x-oneapi-project-id"];

    if (authorization !== "Bearer demo-token") {
      return res.status(401).json({
        success: false,
        code: "INVALID_API_KEY",
        message: "Invalid OneAPI API key",
      });
    }

    if (projectId !== "demo-project") {
      return res.status(403).json({
        success: false,
        code: "INVALID_PROJECT",
        message: "Invalid OneAPI project ID",
      });
    }

    // 2. Validate request
    const { messages, model = "default", temperature = 0.7 } = req.body;

    if (!Array.isArray(messages) || messages.length === 0) {
      return res.status(400).json({
        success: false,
        code: "INVALID_REQUEST",
        message: "Messages are required",
      });
    }

    console.log("\n========== ONEAPI REQUEST ==========");
    console.log("Project:", projectId);
    console.log("Requested model:", model);

    // 3. Simulate primary provider failure
    const prompt = messages
      .map((message) => message.content || "")
      .join(" ");

    const simulateFailure = prompt.includes(
      "[MOCK_PRIMARY_FAILURE]"
    );

    console.log("Primary provider: Gemini");

    let selectedProvider = "gemini";
    let fallbackUsed = false;
    let generatedText;

    if (simulateFailure) {
      console.log("Gemini failed: simulated 503 error");

      // 4. Automatic fallback
      console.log("Switching to OpenAI...");

      selectedProvider = "openai";
      fallbackUsed = true;

      generatedText =
        "Hello! This response was generated by the mock OpenAI fallback provider.";
    } else {
      generatedText =
        "Hello! This response was generated by the mock Gemini primary provider.";
    }

    console.log("Selected provider:", selectedProvider);
    console.log("Fallback used:", fallbackUsed);
    console.log("====================================\n");

    // 5. Return normalized response
    return res.json({
      success: true,
      id: `mock-${Date.now()}`,
      object: "chat.completion",
      model,
      choices: [
        {
          index: 0,
          message: {
            role: "assistant",
            content: generatedText,
          },
          finish_reason: "stop",
        },
      ],
      provider: selectedProvider,
      fallback: {
        attempted: fallbackUsed,
        from: fallbackUsed ? "gemini" : null,
        to: fallbackUsed ? "openai" : null,
      },
      usage: {
        prompt_tokens: 20,
        completion_tokens: 30,
        total_tokens: 50,
      },
    });
  } catch (error) {
    console.error("Mock gateway error:", error);

    return res.status(500).json({
      success: false,
      code: "INTERNAL_ERROR",
      message: "Mock gateway internal error",
    });
  }
});

app.listen(PORT, () => {
  console.log(`Mock OneAPI Gateway running on http://localhost:${PORT}`);
});